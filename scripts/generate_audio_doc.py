def get_faction(cv_id):
    """根据 CV ID 获取阵营"""
    prefix = cv_id // 10000
    if prefix in FACTION_MAP:
        return FACTION_MAP[prefix]
    # 处理 100000+ 的联动角色
    if cv_id >= 1000000:
        prefix2 = cv_id // 100000
        if prefix2 in FACTION_MAP:
            return FACTION_MAP[prefix2]
    return "未知"


def get_ship_type(cv_id):
    """根据 CV ID 获取舰种"""
    # 提取中间的舰种编号
    if cv_id >= 10000 and cv_id < 100000:
        type_code = (cv_id % 10000) // 100
        if type_code in SHIP_TYPE_MAP:
            return SHIP_TYPE_MAP[type_code]
    elif cv_id >= 100000:
        type_code = (cv_id % 100000) // 1000
        if type_code in SHIP_TYPE_MAP:
            return SHIP_TYPE_MAP[type_code]
    return ""


