def parse_cv_map(raw):
    """解析 CV_MAP 原始文本"""
    result = {}
    for chunk in raw.replace('\n', '').split(','):
        chunk = chunk.strip()
        if not chunk or ':' not in chunk:
            continue
        try:
            cid, name = chunk.split(':', 1)
            result[int(cid)] = name.strip()
        except:
            pass
    return result

def get_faction(cid):
    """从 CV ID 提取阵营"""
    if cid < 10000:
        return "TB领航员"
    prefix = cid // 1000
    # 处理科研舰船 (99xxx)
    if prefix == 99:
        # 科研舰根据百位判断阵营
        hundreds = (cid % 1000) // 100
        if hundreds == 0:
            return "科研"
        faction_by_hundreds = {
            1: "白鹰", 2: "皇家", 3: "重樱", 4: "铁血",
            5: "东煌", 6: "撒丁帝国", 7: "北方联合",
            8: "自由鸢尾", 9: "维希教廷"
        }
        return faction_by_hundreds.get(hundreds, "科研")
    # 超巡 (118xx = 白鹰, 18xxx = 撒丁)
    if cid // 100 == 118:
        return "白鹰"
    return FACTION_PREFIX.get(prefix, "未知")

def get_ship_type(cid):
    """从 CV ID 提取舰种"""
    if cid < 10000:
        return "指挥"
    # 科研舰
    if cid // 1000 == 99:
        suffix = cid % 100
        return SHIP_TYPE_SUFFIX.get(suffix // 10, "科研")
    suffix = cid % 1000
    type_code = suffix // 100
    if type_code == 1:
        return "驱逐"
    elif type_code == 2:
        return "轻巡"
    elif type_code == 3:
        return "重巡"
    elif type_code == 4:
        return "战巡"
    elif type_code == 5:
        return "战列"
    elif type_code == 6:
        return "轻航"
    elif type_code == 7:
        return "航母"
    elif type_code == 8:
        return "潜艇"
    elif type_code == 9:
        return "潜艇"
    elif type_code == 12:
        return "维修"
    elif type_code == 13:
        return "重炮"
    elif type_code == 18:
        return "超巡"
    elif type_code == 19:
        return "运输"
    return "其他"

# 主流程
cv_map = parse_cv_map(CV_MAP_RAW)
print(f"CV_MAP entries: {len(cv_map)}")

# 构建中文名→阵营/舰种映射
cn_faction_type = {}
for cid, cn_name in cv_map.items():
    if cid < 1000:
        continue  # 跳过 TB 领航员
    faction = get_faction(cid)
    ship_type = get_ship_type(cid)
    cn_faction_type[cn_name] = {"faction": faction, "type": ship_type}

# 构建拼音→阵营/舰种映射
ship_database = {}
for pinyin, cn_name in SHIP_NAME_MAP.items():
    if cn_name in cn_faction_type:
        ship_database[pinyin] = {
            "cn_name": cn_name,
            "faction": cn_faction_type[cn_name]["faction"],
            "type": cn_faction_type[cn_name]["type"]
        }
    else:
        ship_database[pinyin] = {
            "cn_name": cn_name,
            "faction": "未知",
            "type": "未知"
        }

# 统计
faction_counts = {}
type_counts = {}
unknown_faction = []
unknown_type = []

for k, v in ship_database.items():
    f = v["faction"]
    t = v["type"]
    faction_counts[f] = faction_counts.get(f, 0) + 1
    type_counts[t] = type_counts.get(t, 0) + 1
    if f == "未知":
        unknown_faction.append(k)
    if t == "未知":
        unknown_type.append(k)

print(f"\nTotal ships: {len(ship_database)}")
print(f"\nFactions:")
for f, c in sorted(faction_counts.items(), key=lambda x: -x[1]):
    print(f"  {f}: {c}")
print(f"\nTypes:")
for t, c in sorted(type_counts.items(), key=lambda x: -x[1]):
    print(f"  {t}: {c}")

if unknown_faction:
    print(f"\nUnknown faction ({len(unknown_faction)}):")
    for name in unknown_faction[:20]:
        print(f"  {name} ({ship_database[name]['cn_name']})")

